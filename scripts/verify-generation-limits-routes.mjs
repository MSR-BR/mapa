import assert from 'node:assert/strict';
import { state, requestRoute } from './c111-route-harness.mjs';
state.reset();
const problem = state.workflow.content.elements.find(e => e.type === 'problem_statement');
const oversized = 'Como ' + 'texto '.repeat(100) + '?';
problem.proposedContent = oversized; problem.approvedContent = null; problem.updatedBy = 'ai'; problem.status = 'suggested';
let response = await requestRoute('definition', {action:'save',step:'problem_statement',content:oversized,revision:state.workflow.revision});
assert.equal(response.status,200,await response.clone().text());
assert.equal(state.aiCalls,0);
assert.equal(state.workflow.content.stepDrafts.problem_statement.unit.elements[0].proposedContent,oversized);
response = await requestRoute('definition', {action:'validate',step:'problem_statement',content:oversized,revision:state.workflow.revision});
assert.equal(response.status,400);
response = await requestRoute('regenerateCard', {step:'problem_statement',targetId:'problem',instruction:'Como esclarecer o problema delimitado?',revision:state.workflow.revision});
assert.equal(response.status,200,await response.clone().text());
assert.equal(state.cardInput.card.element.proposedContent,oversized);
assert.ok(state.workflow.content.stepDrafts.problem_statement.unit.elements[0].proposedContent.length<=500);
const before = JSON.stringify(state.workflow);
response = await requestRoute('regenerateCard', {step:'problem_statement',targetId:'problem',instruction:'x'.repeat(600),revision:state.workflow.revision});
assert.equal(response.status,502);
assert.equal(JSON.stringify(state.workflow),before);
state.reset();
response = await requestRoute('definition', {action:'save',step:'problem_statement',content:oversized,revision:state.workflow.revision});
assert.equal(response.status,400); assert.equal(state.writes,0);
console.log('C118: legacy oversized draft saved without expansion, confirmation blocked, isolated regeneration succeeds, oversized result preserves saved content; new oversized draft rejected. No external calls.');
